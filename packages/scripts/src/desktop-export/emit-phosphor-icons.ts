import {
  COMPASS_KIT_GENERATED_DIR,
  COMPASS_KIT_RESOURCES_DIR,
} from "@scripts/desktop-export/paths";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Keep in sync with web `@phosphor-icons/react` CSR imports used in parity surfaces. */
export const PHOSPHOR_ICON_NAMES = [
  "ArrowClockwise",
  "ArrowCounterClockwise",
  "ArrowUDownLeft",
  "Calendar",
  "CalendarDots",
  "Command",
  "Compass",
  "Copy",
  "Eye",
  "EyeSlash",
  "Gear",
  "HourglassSimple",
  "Info",
  "Keyboard",
  "MapPin",
  "MoonStars",
  "Plus",
  "SidebarSimple",
  "Sun",
  "Trash",
  "Users",
  "VideoCamera",
  "X",
] as const;

export type PhosphorIconName = (typeof PHOSPHOR_ICON_NAMES)[number];

const phosphorDefsDir = (): string => {
  const candidates = [
    join(process.cwd(), "node_modules/@phosphor-icons/react/dist/defs"),
    join(
      process.cwd(),
      "apps/calendar-web/node_modules/@phosphor-icons/react/dist/defs",
    ),
  ];
  for (const dir of candidates) {
    try {
      readFileSync(join(dir, "Calendar.es.js"), "utf8");
      return dir;
    } catch {
      // try next
    }
  }
  throw new Error("Could not locate @phosphor-icons/react dist/defs");
};

const extractRegularPath = (source: string): string => {
  const match = source.match(/"regular",[\s\S]*?d:\s*"([^"]+)"/);
  if (!match) {
    throw new Error("Missing regular weight path in phosphor def");
  }
  return match[1];
};

const swiftCaseName = (icon: PhosphorIconName): string => {
  const first = icon[0]?.toLowerCase() ?? "";
  return first + icon.slice(1);
};

export const emitPhosphorIconsSwift = (): string => {
  const paths: Record<PhosphorIconName, string> = {} as Record<
    PhosphorIconName,
    string
  >;
  const defsDir = phosphorDefsDir();
  for (const name of PHOSPHOR_ICON_NAMES) {
    const defPath = join(defsDir, `${name}.es.js`);
    const source = readFileSync(defPath, "utf8");
    paths[name] = extractRegularPath(source);
  }

  const cases = PHOSPHOR_ICON_NAMES.map((name) => {
    const escaped = paths[name].replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    return `        case .${swiftCaseName(name)}:\n            return "${escaped}"`;
  }).join("\n");

  const enumCases = PHOSPHOR_ICON_NAMES.map(
    (name) => `    case ${swiftCaseName(name)}`,
  ).join("\n");

  return `// Generated by bun cli desktop:export. Do not edit.
import Foundation

public enum PhosphorIcon: String, Sendable, CaseIterable {
${enumCases}

    public var pathData: String {
        switch self {
${cases}
        }
    }
}
`;
};

export const emitPhosphorSvgFiles = (): {
  path: string;
  contents: string;
}[] => {
  const outDir = join(COMPASS_KIT_RESOURCES_DIR, "Phosphor");
  const files: { path: string; contents: string }[] = [];
  const defsDir = phosphorDefsDir();
  for (const name of PHOSPHOR_ICON_NAMES) {
    const defPath = join(defsDir, `${name}.es.js`);
    const source = readFileSync(defPath, "utf8");
    const d = extractRegularPath(source);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor"><path d="${d}"/></svg>\n`;
    files.push({ path: join(outDir, `${name}.svg`), contents: svg });
  }
  return files;
};

export const PHOSPHOR_ICONS_SWIFT_PATH = join(
  COMPASS_KIT_GENERATED_DIR,
  "PhosphorIcon.swift",
);
